/**
 * P1: Submission Pack Exporter Module
 * Exports Evidence Matrix, APA References, Rubric Summary, and Activity Log.
 * Supported formats: Microsoft Word (.docx/.doc HTML package), CSV, and clean HTML.
 */

import { arrayToCSV, downloadFile } from '../storage/export-import.js';
import { MATRIX_COLUMNS } from './evidence-matrix.js';
import { getAllItems } from '../storage/db.js';

export async function exportMatrixToCSV(assignment, rows) {
  const visibleCols = MATRIX_COLUMNS.filter(c => c.visible);
  const headers = visibleCols.map(c => c.label);
  const data = rows.map(r => visibleCols.map(c => r[c.id] || ''));

  const csv = arrayToCSV(headers, data);
  const filename = `${assignment.title.replace(/[^a-zA-Z0-9_-]/g, '_')}_Evidence_Matrix.csv`;
  downloadFile(csv, filename, 'text/csv');
  return true;
}

